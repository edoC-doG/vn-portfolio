// Runs before `next dev` and `next build` (predev / prebuild):
//   public/models/{mid,low}/*.glb   copies of assets/models (the high tier is not served)
//   public/textures/*.{jpg,png}     copies of assets/textures
//   src/scene/journey.js            the 3D engine: prototype/fly/app.js with the build data filled in and plain-file
//                                   asset loading (ASSET_BASE '/'), so the prototype and the site share one scene source
// All three are generated and not committed. Files that are already up to date are left alone.
import fs from 'fs';
import path from 'path';
import { injectApp, ROOT } from '../../prototype/fly/inject.mjs';

const web = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
let copied = 0;

function mirror(src, dst, keep) {
  fs.mkdirSync(dst, { recursive: true });
  const want = new Set(fs.readdirSync(src).filter(keep));
  for (const f of want) {
    const a = path.join(src, f), b = path.join(dst, f), sa = fs.statSync(a);
    if (fs.existsSync(b)) { const sb = fs.statSync(b); if (sb.size === sa.size && sb.mtimeMs >= sa.mtimeMs) continue; }
    fs.copyFileSync(a, b); copied++;
  }
  for (const f of fs.readdirSync(dst)) if (!want.has(f)) fs.rmSync(path.join(dst, f)); // a model removed from assets/ goes from public/ too
  return want.size;
}

const nModels = ['mid', 'low'].map((t) => mirror(path.join(ROOT, 'assets/models', t), path.join(web, 'public/models', t), (f) => f.endsWith('.glb')));
const nTex = mirror(path.join(ROOT, 'assets/textures'), path.join(web, 'public/textures'), (f) => /\.(jpe?g|png)$/.test(f));

const { code, modelList, credits } = injectApp(fs.readFileSync(path.join(ROOT, 'prototype/fly/app.js'), 'utf8'), { assetBase: '/' });
const out = path.join(web, 'src/scene/journey.js');
const body = `// Generated by web/scripts/sync.mjs from prototype/fly/app.js. Edit that file, not this one.\n/* eslint-disable */\n// @ts-nocheck\n${code}`;
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);

console.log(`sync: ${nModels.join('+')} models (mid+low), ${nTex} textures, ${copied} files copied; engine with ${modelList.length} models, ${credits.length} credits`);
